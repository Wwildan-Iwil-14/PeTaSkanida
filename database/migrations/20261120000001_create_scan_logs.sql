-- Log scan QR/barcode tamu oleh petugas (dari HP).
-- Setiap scan dicatat di sini, lalu dashboard admin (laptop) menerima
-- notifikasi real-time. Tabel ini sengaja TIDAK menyimpan data pribadi tamu;
-- detail tamu diambil lewat backend yang memerlukan login admin.

CREATE TABLE IF NOT EXISTS public.scan_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint REFERENCES public.req_pending(id) ON DELETE CASCADE,
  kode text NOT NULL,
  hasil text NOT NULL,            -- valid | pending | ditolak | selesai | tidak_ditemukan
  scanned_by text,                -- nama petugas yang scan
  device_id text,                 -- id perangkat pemindai (agar HP tidak menerima notif dari scan-nya sendiri)
  scanned_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS scan_logs_scanned_at_idx ON public.scan_logs (scanned_at DESC);

ALTER TABLE public.scan_logs ENABLE ROW LEVEL SECURITY;

-- Frontend memakai anon key hanya untuk menerima sinyal real-time.
DROP POLICY IF EXISTS "select_scan_logs" ON public.scan_logs;
CREATE POLICY "select_scan_logs" ON public.scan_logs
  FOR SELECT TO anon, authenticated USING (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.scan_logs;
