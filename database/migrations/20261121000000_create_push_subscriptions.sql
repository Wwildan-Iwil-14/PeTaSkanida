-- Notifikasi Web Push: daftar browser/admin yang aktif berlangganan.
-- Baris dibuat & dihapus oleh backend memakai service role key.
-- Tidak ada pesan notifikasi yang disimpan di sini — hanya endpoint browser
-- dan kunci enkripsi (sangat kecil, satu baris per perangkat).

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint text NOT NULL UNIQUE,
  subscription jsonb NOT NULL,
  admin_user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS push_subscriptions_admin_idx
  ON public.push_subscriptions (admin_user_id);

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

