-- ============================================
-- PeTa SKANIDA - Complete Database Schema
-- ============================================
-- Run this file in Supabase SQL Editor to set up
-- the database from scratch.
--
-- Autentikasi admin memakai Supabase Auth (schema auth / GoTrue):
-- akun & password diurus Supabase, tabel admins hanya menyimpan profil.
-- ============================================

-- ============================================
-- TABLES
-- ============================================

-- req_pending: Tabel master, semua request kunjungan masuk ke sini
CREATE TABLE IF NOT EXISTS public.req_pending (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  dihubungi boolean NOT NULL DEFAULT false,
  dihubungi_at timestamptz,
  surat_tugas_url text,
  surat_tugas_drive_id text,
  surat_tugas_nama text
);

-- req_acc: Request yang diterima admin dan masih aktif / belum selesai
-- (FK ke req_pending, CASCADE delete)
CREATE TABLE IF NOT EXISTS public.req_acc (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  surat_tugas_url text,
  surat_tugas_drive_id text,
  surat_tugas_nama text,
  CONSTRAINT fk_req_acc_pending FOREIGN KEY (id)
    REFERENCES public.req_pending(id) ON DELETE CASCADE
);

-- req_reject: Request yang ditolak admin (FK ke req_pending, CASCADE delete)
CREATE TABLE IF NOT EXISTS public.req_reject (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  surat_tugas_url text,
  surat_tugas_drive_id text,
  surat_tugas_nama text,
  CONSTRAINT fk_req_reject_pending FOREIGN KEY (id)
    REFERENCES public.req_pending(id) ON DELETE CASCADE
);

-- riwayat: Arsip kunjungan yang sudah selesai dan permintaan yang ditolak
-- (FK ke req_pending, CASCADE delete)
CREATE TABLE IF NOT EXISTS public.riwayat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  surat_tugas_url text,
  surat_tugas_drive_id text,
  surat_tugas_nama text,
  CONSTRAINT fk_riwayat_pending FOREIGN KEY (id)
    REFERENCES public.req_pending(id) ON DELETE CASCADE
);

-- admins: Profil admin (nama, role, fitur) yang dihubungkan ke akun Supabase Auth.
-- Login & password diurus Supabase Auth (auth.users), bukan tabel ini.
-- Baris profil dibuat oleh skrip backend: npm run admin:create
CREATE TABLE IF NOT EXISTS public.admins (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id uuid UNIQUE REFERENCES auth.users (id) ON DELETE CASCADE,
  username text UNIQUE,                -- arsip username lama (opsional)
  email text,
  nama text NOT NULL,
  role text NOT NULL DEFAULT 'admin'
    CHECK (role IN ('petugas', 'admin', 'super_admin')),
  -- Daftar fitur per akun. NULL = pakai fitur bawaan role.
  features text[],
  created_at timestamptz DEFAULT now()
);

-- scan_logs: Log scan QR/barcode tamu oleh petugas (HP) → notifikasi real-time ke admin
CREATE TABLE IF NOT EXISTS public.scan_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint REFERENCES public.req_pending(id) ON DELETE CASCADE,
  kode text NOT NULL,
  hasil text NOT NULL,
  scanned_by text,
  device_id text,
  scanned_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS scan_logs_scanned_at_idx ON public.scan_logs (scanned_at DESC);
ALTER TABLE public.scan_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "select_scan_logs" ON public.scan_logs;
CREATE POLICY "select_scan_logs" ON public.scan_logs
  FOR SELECT TO anon, authenticated USING (true);
ALTER PUBLICATION supabase_realtime ADD TABLE public.scan_logs;

-- push_subscriptions: perangkat admin yang aktif menerima notifikasi browser.
-- Hanya backend (service role) yang mengakses; tidak ada policy untuk anon.
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint text NOT NULL UNIQUE,
  subscription jsonb NOT NULL,
  admin_user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS push_subscriptions_admin_idx
  ON public.push_subscriptions (admin_user_id);
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

-- ============================================
-- ROW LEVEL SECURITY
-- ============================================

-- Aktifkan RLS untuk semua tabel
ALTER TABLE public.req_pending ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.req_acc ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.req_reject ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.riwayat ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;

-- Policy tabel request: anon & authenticated hanya boleh MEMBACA.
-- Ini dipakai frontend untuk real-time, sedangkan operasi tulis
-- (insert request, approve/reject) dilakukan backend memakai service role key.
DROP POLICY IF EXISTS "enable_all_req_pending" ON public.req_pending;
DROP POLICY IF EXISTS "enable_all_req_acc" ON public.req_acc;
DROP POLICY IF EXISTS "enable_all_req_reject" ON public.req_reject;
DROP POLICY IF EXISTS "enable_all_riwayat" ON public.riwayat;

DROP POLICY IF EXISTS "select_req_pending" ON public.req_pending;
DROP POLICY IF EXISTS "select_req_acc" ON public.req_acc;
DROP POLICY IF EXISTS "select_req_reject" ON public.req_reject;
DROP POLICY IF EXISTS "select_riwayat" ON public.riwayat;

CREATE POLICY "select_req_pending" ON public.req_pending
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "select_req_acc" ON public.req_acc
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "select_req_reject" ON public.req_reject
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "select_riwayat" ON public.riwayat
  FOR SELECT TO anon, authenticated USING (true);

-- Tabel admins: anon dilarang membaca. Admin yang login hanya boleh
-- membaca baris profil miliknya sendiri (auth.uid() = user_id).
DROP POLICY IF EXISTS "select_own_admin_profile" ON public.admins;
CREATE POLICY "select_own_admin_profile" ON public.admins
  FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

-- ============================================
-- REALTIME
-- ============================================

-- Aktifkan real-time untuk tabel request
-- Agar dashboard admin otomatis update ketika ada data baru
ALTER PUBLICATION supabase_realtime ADD TABLE public.req_pending;
ALTER PUBLICATION supabase_realtime ADD TABLE public.req_acc;
ALTER PUBLICATION supabase_realtime ADD TABLE public.req_reject;

