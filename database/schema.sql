-- Enable pgcrypto for password hashing
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ============================================
-- TABLES
-- ============================================

-- req_pending: Tabel master, semua request kunjungan masuk ke sini
CREATE TABLE IF NOT EXISTS public.req_pending (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1
);

-- req_acc: Request yang diterima admin (FK ke req_pending, CASCADE delete)
CREATE TABLE IF NOT EXISTS public.req_acc (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  CONSTRAINT fk_req_acc_pending FOREIGN KEY (id)
    REFERENCES public.req_pending(id) ON DELETE CASCADE
);

-- req_reject: Request yang ditolak admin (FK ke req_pending, CASCADE delete)
CREATE TABLE IF NOT EXISTS public.req_reject (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  CONSTRAINT fk_req_reject_pending FOREIGN KEY (id)
    REFERENCES public.req_pending(id) ON DELETE CASCADE
);

-- riwayat: Arsip semua request yang sudah diproses (FK ke req_pending, CASCADE delete)
CREATE TABLE IF NOT EXISTS public.riwayat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text,
  email text,
  no_hp text,
  tujuan text,
  keperluan text,
  tanggal date DEFAULT CURRENT_DATE,
  waktu text,
  jumlah integer DEFAULT 1,
  CONSTRAINT fk_riwayat_pending FOREIGN KEY (id)
    REFERENCES public.req_pending(id) ON DELETE CASCADE
);

-- admins: Daftar akun admin dengan password ter-hash (bcrypt)
CREATE TABLE IF NOT EXISTS public.admins (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  username text UNIQUE NOT NULL,
  email text,
  password_hash text NOT NULL,
  nama text NOT NULL,
  created_at timestamptz DEFAULT now()
);

